-- =====================================================================
-- Ufinet - Modelo de datos de ofertas (H2 en memoria, SQL estándar)
-- Oferta 1 ---- 1..5 Servicio
-- =====================================================================

DROP TABLE IF EXISTS servicio;
DROP TABLE IF EXISTS oferta;

CREATE TABLE oferta (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente  VARCHAR(100) NOT NULL,
    estado   VARCHAR(20)  NOT NULL DEFAULT 'BORRADOR',
    version  BIGINT       NOT NULL DEFAULT 0,               -- bloqueo optimista (@Version)
    CONSTRAINT ck_oferta_cliente CHECK (CHAR_LENGTH(TRIM(cliente)) > 0),
    CONSTRAINT ck_oferta_estado  CHECK (estado IN ('BORRADOR', 'PRESENTADA', 'NO_VIABLE'))
);

CREATE TABLE servicio (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    oferta_id    BIGINT        NOT NULL,
    tipo         VARCHAR(20)   NOT NULL,
    mbps         INTEGER       NOT NULL,
    plazo_meses  INTEGER       NOT NULL,
    viable       BOOLEAN       NOT NULL,
    mrc          DECIMAL(12,2) NOT NULL,                     -- calculado por el backend
    CONSTRAINT fk_servicio_oferta FOREIGN KEY (oferta_id) REFERENCES oferta (id) ON DELETE CASCADE,
    CONSTRAINT ck_servicio_tipo   CHECK (tipo IN ('INTERNET', 'CAPACIDAD')),
    CONSTRAINT ck_servicio_mbps   CHECK (mbps BETWEEN 10 AND 10000),
    CONSTRAINT ck_servicio_plazo  CHECK (plazo_meses IN (12, 24, 36)),
    CONSTRAINT ck_servicio_mrc    CHECK (mrc >= 0)
);

CREATE INDEX ix_servicio_oferta ON servicio (oferta_id);
